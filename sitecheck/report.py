"""Static HTML report (single run or before/after comparison). No JS, no external assets."""
from __future__ import annotations

from html import escape

SAMPLE_LABEL = "SAMPLE DATA (illustrative, not a real scan)"
SAMPLE_BANNER = f'<div class="sample" role="note">{SAMPLE_LABEL}</div>'


def is_sample(run):
    return bool(run.get("sample")) or "SAMPLE" in str(run.get("note", "")).upper()


RANK = {"FAIL": 0, "PARTIAL": 1, "WARN": 2, "PASS": 3, "SKIP": None}

CSS = """
:root{--bg:#0b0f1a;--card:#121829;--fg:#e6e9f2;--muted:#8a93ab;--cyan:#22d3ee;--purple:#a78bfa;
--pass:#34d399;--warn:#fbbf24;--partial:#60a5fa;--fail:#f87171;--skip:#6b7280}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif}
main{max-width:1000px;margin:auto;padding:32px 20px}
h1{margin:0 0 4px;background:linear-gradient(90deg,var(--cyan),var(--purple));-webkit-background-clip:text;background-clip:text;color:transparent}
.sub{color:var(--muted);margin-bottom:24px}.card{background:var(--card);border:1px solid #232b45;border-radius:12px;padding:16px 20px;margin:16px 0}
table{width:100%;border-collapse:collapse}th,td{text-align:left;padding:8px;border-bottom:1px solid #232b45;vertical-align:top}
th{color:var(--cyan);font-weight:600}.b{display:inline-block;padding:2px 10px;border-radius:999px;font-weight:700;font-size:12px;color:#0b0f1a}
.PASS{background:var(--pass)}.WARN{background:var(--warn)}.PARTIAL{background:var(--partial)}.FAIL{background:var(--fail)}.SKIP,.NA{background:var(--skip)}
.chips span{margin-right:10px}.up{color:var(--pass)}.down{color:var(--fail)}.same{color:var(--muted)}
footer,.sample{background:#3b1d5e;border:1px solid var(--purple);color:#f5f3ff;font-weight:700;padding:8px 14px;border-radius:8px;margin-bottom:16px}
footer,.note{color:var(--muted);font-size:13px}code{color:var(--purple)}
"""

NOTE = ("Passive checks only: one request per check, no load testing, fuzzing or login. "
        "Response time and Lighthouse are single samples and vary between runs. A PASS means the "
        "check found nothing wrong, not that the site is secure. PARTIAL means present but not "
        "enforced (for example, a report-only CSP).")


def badge(st):
    return f'<span class="b {escape(st)}">{escape(st)}</span>'


def _chips(summary):
    return '<div class="chips">' + "".join(f"<span>{badge(k)} {v}</span>" for k, v in summary.items() if v) + "</div>"


def _page(title, sub, body, sample=False):
    return (f"<!doctype html><html lang=en><head><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>"
            f"<title>{escape(title)}</title><style>{CSS}</style></head><body><main><h1>{escape(title)}</h1>"
            f"<div class=sub>{sub}</div>{SAMPLE_BANNER if sample else ''}{body}<p class=note>{escape(NOTE)}</p>"
            f"<footer>Generated by sitecheck.</footer></main></body></html>")


def _header_rows(check):
    rows = check.get("data", {}).get("headers")
    if not rows:
        return ""
    return "<table>" + "".join(f"<tr><td><code>{escape(h)}</code></td><td>{badge(s)}</td></tr>" for h, s in rows.items()) + "</table>"


def render_single(run, label=""):
    rows = "".join(
        f"<tr><td>{escape(c['name'])}</td><td>{badge(c['status'])}</td><td>{escape(c['detail'])}{_header_rows(c)}</td></tr>"
        for c in run["checks"])
    body = (f"<div class=card>{_chips(run['summary'])}</div><div class=card><table>"
            f"<tr><th>Check</th><th>Status</th><th>Detail</th></tr>{rows}</table></div>")
    sub = f"{escape(run['url'])} &middot; {escape(run['checked_at'])}" + (f" &middot; {escape(label)}" if label else "")
    return _page("Website check", sub, body, is_sample(run))


def compare(before, after):
    b = {c["name"]: c for c in before["checks"]}
    a = {c["name"]: c for c in after["checks"]}
    out = []
    for name in list(dict.fromkeys([*b, *a])):
        sb = b.get(name, {}).get("status", "NA")
        sa = a.get(name, {}).get("status", "NA")
        rb, ra = RANK.get(sb), RANK.get(sa)
        change = "improved" if rb is not None and ra is not None and ra > rb else \
                 "regressed" if rb is not None and ra is not None and ra < rb else "unchanged" if sb == sa else "changed"
        out.append({"name": name, "before": sb, "after": sa, "change": change,
                    "before_detail": b.get(name, {}).get("detail", ""), "after_detail": a.get(name, {}).get("detail", "")})
    return out


def render_compare(before, after, label=""):
    diff = compare(before, after)
    cls = {"improved": "up", "regressed": "down"}
    rows = "".join(
        f"<tr><td>{escape(d['name'])}</td><td>{badge(d['before'])}<br><small>{escape(d['before_detail'])}</small></td>"
        f"<td>{badge(d['after'])}<br><small>{escape(d['after_detail'])}</small></td>"
        f"<td class={cls.get(d['change'], 'same')}>{d['change']}</td></tr>" for d in diff)
    counts = {k: sum(d["change"] == k for d in diff) for k in ("improved", "regressed", "unchanged")}
    body = (f"<div class=card><table><tr><th></th><th>Before ({escape(before['checked_at'])})</th><th>After ({escape(after['checked_at'])})</th></tr>"
            f"<tr><td>Summary</td><td>{_chips(before['summary'])}</td><td>{_chips(after['summary'])}</td></tr></table></div>"
            f"<div class=card>{counts['improved']} improved, {counts['regressed']} regressed, {counts['unchanged']} unchanged</div>"
            f"<div class=card><table><tr><th>Check</th><th>Before</th><th>After</th><th>Change</th></tr>{rows}</table></div>")
    sub = escape(after["url"]) + (f" &middot; {escape(label)}" if label else "")
    return _page("Before / after", sub, body, is_sample(before) or is_sample(after))
